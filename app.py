"""
Titanic Survival Predictor - Streamlit App
Run with:  streamlit run app.py
Requires titanic_model.pkl, scaler.pkl, le_sex.pkl, le_embarked.pkl,
le_title.pkl, model_accuracy.pkl (generated by train_model.py) in the same folder.
"""

import streamlit as st
import pandas as pd
import joblib

st.set_page_config(page_title="Titanic Survival Predictor", page_icon="🚢", layout="wide")

model = joblib.load("titanic_model.pkl")
scaler = joblib.load("scaler.pkl")
le_sex = joblib.load("le_sex.pkl")
le_embarked = joblib.load("le_embarked.pkl")
le_title = joblib.load("le_title.pkl")
model_accuracy = joblib.load("model_accuracy.pkl")

st.title("🚢 Titanic Survival Predictor")
st.write("Predict whether a passenger would have survived the Titanic shipwreck, based on their profile.")

st.sidebar.header("Passenger Information")

pclass = st.sidebar.selectbox("Passenger Class", [1, 2, 3], index=2)
sex = st.sidebar.selectbox("Gender", ["male", "female"])
age = st.sidebar.slider("Age", 0, 80, 28)
sibsp = st.sidebar.slider("Siblings / Spouses aboard", 0, 8, 0)
parch = st.sidebar.slider("Parents / Children aboard", 0, 6, 0)
fare = st.sidebar.slider("Fare paid (£)", 0.0, 512.0, 32.0)
embarked = st.sidebar.selectbox("Port of Embarkation", ["S", "C", "Q"])
title = st.sidebar.selectbox("Title", ["Mr", "Mrs", "Miss", "Master", "Rare"])
has_cabin = st.sidebar.selectbox("Had a recorded Cabin?", ["Yes", "No"])

family_size = sibsp + parch + 1
is_alone = 1 if family_size == 1 else 0
has_cabin_val = 1 if has_cabin == "Yes" else 0

input_df = pd.DataFrame({
    "Pclass": [pclass],
    "Sex": le_sex.transform([sex]),
    "Age": [age],
    "SibSp": [sibsp],
    "Parch": [parch],
    "Fare": [fare],
    "Embarked": le_embarked.transform([embarked]),
    "Title": le_title.transform([title]),
    "FamilySize": [family_size],
    "IsAlone": [is_alone],
    "HasCabin": [has_cabin_val],
})

# Scale numeric columns exactly as done during training
input_df[["Age", "Fare", "FamilySize"]] = scaler.transform(input_df[["Age", "Fare", "FamilySize"]])

# Reorder columns to match the exact order the model was trained on
input_df = input_df[model.feature_names_in_]

if st.sidebar.button("Predict Survival"):
    prediction = model.predict(input_df)[0]
    proba = model.predict_proba(input_df)[0]

    col1, col2 = st.columns(2)

    with col1:
        if prediction == 1:
            st.success("### Prediction: SURVIVED ✅")
        else:
            st.error("### Prediction: DID NOT SURVIVE ☠️")
        st.write(f"**Prediction Confidence:** {proba[prediction] * 100:.2f}%")
        st.write(f"**Model Accuracy (test set):** {model_accuracy * 100:.2f}%")

    with col2:
        st.write("#### Passenger Profile")
        st.table(pd.DataFrame({
            "Feature": ["Class", "Sex", "Age", "Siblings/Spouses", "Parents/Children",
                        "Fare", "Embarked", "Title", "Family Size"],
            "Value": [pclass, sex, age, sibsp, parch, fare, embarked, title, family_size]
        }))

    st.write("#### Survival Probability")
    prob_df = pd.DataFrame({
        "Outcome": ["Did Not Survive", "Survived"],
        "Probability": [proba[0], proba[1]]
    })
    st.bar_chart(prob_df.set_index("Outcome"))
else:
    st.info("Set the passenger details in the sidebar and click **Predict Survival**.")